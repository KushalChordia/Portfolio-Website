interface PixelIconProps {
  name: PixelIconName;
  /** Rendered size in px. The 16x16 grid scales cleanly at 16, 24, 32, 48. */
  size?: number;
  className?: string;
}

/**
 * Decorative by default: every icon on this site sits beside a text label, so
 * announcing it would only duplicate what the label already says.
 */
export function PixelIcon({ name, size = 24, className }: PixelIconProps) {
  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      className={cn("shrink-0", className)}
    >
      {ICONS[name].map(([x, y, w, tone], index) => (
        <rect
          key={index}
          x={x}
          y={y}
          width={w}
          height={1}
          fill={tone === 1 ? "currentColor" : "var(--color-chalk)"}
        />
      ))}
    </svg>
  );
}